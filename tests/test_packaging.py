"""Packaging regression tests for pdomain-ocr-simple-gui.

These assert invariants about how the project is *packaged*, not about the
running app.

Regression guard for the built frontend SPA: hatchling only ships files from
``src/pdomain_ocr_simple_gui/frontend/`` if that directory is explicitly
included via the ``artifacts`` field in both the global ``[tool.hatch.build]``
section (or per-target) and (belt-and-suspenders) via
``[tool.hatch.build.targets.wheel.force-include]``.

Because ``frontend/`` is gitignored (generated by ``just frontend-build``),
hatchling's default VCS-based include logic silently omits it. The symptom at
install time is a 503 response to every GET request because the static files
are absent.

The RELEASE BUILD PATH:
  1. ``just build`` runs ``frontend-build`` (vite), then ``uv build --sdist``
     and ``uv build --wheel`` (both from the git source tree).
  2. By default ``uv build`` (without explicit flags) builds the sdist from
     source and then builds the wheel *from the sdist* in a temporary non-git
     directory. That pipeline is also tested here (``test_wheel_from_sdist_*``).

The failure mode of ``b8a2b5f`` (wheel-only ``artifacts``) was:
  - Local plain ``uv build`` produced 78 frontend files in wheel (passes locally)
  - CI published wheel had 0 frontend files (fails on release)

This file exercises both build paths to catch regressions early.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import tarfile
import zipfile
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKAGE_DIR = REPO_ROOT / "src" / "pdomain_ocr_simple_gui"
FRONTEND_SRC = PACKAGE_DIR / "frontend"

# Minimum number of frontend assets expected in a full build.
# A fresh ``just frontend-build`` produces 78 files (index.html +
# manifest.webmanifest + ~76 asset files). Use a conservative floor so the
# assertion does not break on minor font/chunk count changes, but large enough
# to catch a "zero files" or "one file only" regression.
MIN_FRONTEND_FILE_COUNT = 40


def _require_frontend(test_name: str) -> None:
    """Skip *test_name* when the frontend has not been built yet."""
    if not (FRONTEND_SRC / "index.html").exists():
        pytest.skip(
            f"{test_name}: frontend/index.html not present -- "
            + "run `just frontend-build` first. "
            + "This test is skipped in pure-Python CI runs without a prior build step."
        )


def _count_frontend_in_wheel(wheel_path: Path) -> tuple[int, bool]:
    """Return (frontend_file_count, has_index_html) for *wheel_path*."""
    with zipfile.ZipFile(wheel_path) as zf:
        names = zf.namelist()
    fe = [n for n in names if "/frontend/" in n]
    has_index = any(n.endswith("pdomain_ocr_simple_gui/frontend/index.html") for n in names)
    return len(fe), has_index


def _count_frontend_in_sdist(sdist_path: Path) -> tuple[int, bool]:
    """Return (frontend_file_count_in_src_subdir, has_index_html) for *sdist_path*.

    Only counts files under ``src/pdomain_ocr_simple_gui/frontend/`` (the built
    SPA), not under the vite source tree at ``frontend/``.
    """
    with tarfile.open(sdist_path) as tf:
        members = tf.getnames()
    fe = [m for m in members if "src/pdomain_ocr_simple_gui/frontend/" in m]
    has_index = any(m.endswith("src/pdomain_ocr_simple_gui/frontend/index.html") for m in members)
    return len(fe), has_index


def _copy_tracked_project(destination: Path) -> None:
    """Copy tracked project files to *destination* without its Git metadata."""
    tracked_files = subprocess.run(
        ["git", "ls-files", "-z"],
        cwd=REPO_ROOT,
        capture_output=True,
        check=True,
        text=True,
    ).stdout.split("\0")
    for relative_path in tracked_files:
        if not relative_path:
            continue
        source = REPO_ROOT / relative_path
        target = destination / relative_path
        target.parent.mkdir(parents=True, exist_ok=True)
        _ = shutil.copy2(source, target)


def _write_generated_packaging_state(project_root: Path) -> set[str]:
    """Create generated state whose presence in an archive is a packaging leak."""
    generated_files = {
        ".docgraph/index.db": "generated index\n",
        ".worktrees/fixture/README": "generated worktree state\n",
        ".venv/pyvenv.cfg": "generated environment\n",
        ".venv-container/pyvenv.cfg": "generated environment\n",
        ".venv-review/pyvenv.cfg": "generated environment\n",
        "node_modules/root-package/index.js": "generated dependency\n",
        "frontend/node_modules/frontend-package/index.js": "generated dependency\n",
        ".ci-ai.log": "generated log\n",
        ".coverage": "generated coverage\n",
        ".coverage.packaging": "generated coverage\n",
        ".cache/tool/state.json": "generated cache\n",
        ".pytest_cache/v/cache/nodeids": "generated cache\n",
        ".ruff_cache/content": "generated cache\n",
        ".mypy_cache/3.13/cache.json": "generated cache\n",
        ".basedpyright/baseline.json": "generated checker state\n",
        ".basedpyright/cache.json": "generated cache\n",
        "src/pdomain_ocr_simple_gui/__pycache__/app.cpython-313.pyc": "generated bytecode\n",
        "src/pdomain_ocr_simple_gui/__pycache__/app.cpython-313.pyo": "generated bytecode\n",
        "src/pdomain_ocr_simple_gui/frontend/index.html": "<main>SPA</main>\n",
        "src/pdomain_ocr_simple_gui/frontend/assets/app.js": "export {};\n",
    }
    for relative_path, content in generated_files.items():
        path = project_root / relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        _ = path.write_text(content, encoding="utf-8")
    return set(generated_files)


def _sdist_members(sdist_path: Path) -> set[str]:
    """Return all sdist paths relative to its one project-root directory."""
    with tarfile.open(sdist_path) as archive:
        members = archive.getnames()
    top_level_directories = {member.split("/", maxsplit=1)[0] for member in members}
    assert len(top_level_directories) == 1, (
        f"sdist has unexpected root paths: {sorted(top_level_directories)}"
    )
    root_directory = top_level_directories.pop()
    return {member.removeprefix(f"{root_directory}/") for member in members if member != root_directory}


def _wheel_members(wheel_path: Path) -> set[str]:
    """Return all member paths in *wheel_path*."""
    with zipfile.ZipFile(wheel_path) as archive:
        return set(archive.namelist())


def _assert_members_present(*, members: set[str], required: set[str], archive_name: str) -> None:
    """Assert that *archive_name* retains intended shipping inputs."""
    missing = required - members
    assert not missing, f"{archive_name} is missing required members: {sorted(missing)}"


def _assert_no_generated_members(*, members: set[str], archive_name: str) -> None:
    """Assert that *archive_name* has no generated state or tool caches."""
    prohibited_markers = (
        ".docgraph/",
        ".worktrees/",
        ".venv/",
        ".venv-container/",
        ".venv-review/",
        "node_modules/",
        "frontend/node_modules/",
        ".ci-ai.log",
        ".coverage",
        ".cache/",
        ".pytest_cache/",
        ".ruff_cache/",
        ".mypy_cache/",
        ".basedpyright/",
        "__pycache__/",
    )
    leaked = sorted(
        member
        for member in members
        if member.endswith((".pyc", ".pyo")) or any(marker in member for marker in prohibited_markers)
    )
    assert not leaked, f"{archive_name} leaked generated members: {leaked}"


