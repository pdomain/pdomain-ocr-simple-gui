def test_pyproject_artifacts_includes_frontend() -> None:
    """``pyproject.toml`` must declare an ``artifacts`` glob covering the frontend.

    This lightweight static check catches a misconfiguration before a wheel
    build is attempted. If the artifacts entry is absent, hatchling silently
    omits the gitignored frontend/ directory and users see HTTP 503 on every
    page load after ``uv tool install``.
    """
    pyproject = (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    assert "artifacts" in pyproject, (
        "pyproject.toml must declare `artifacts` (in [tool.hatch.build] or "
        "[tool.hatch.build.targets.wheel]) so the gitignored frontend/ build "
        "output ships in the wheel. Without it every `uv tool install` produces "
        "a 503-only app."
    )
    assert "pdomain_ocr_simple_gui/frontend" in pyproject, (
        "pyproject.toml artifacts glob must cover "
        "src/pdomain_ocr_simple_gui/frontend/** so the built SPA ships."
    )


def test_just_build_uses_explicit_sdist_and_wheel() -> None:
    """The ``build`` just recipe must build sdist and wheel separately from source.

    ``uv build`` (default, without explicit flags) builds the wheel *from the
    sdist* in a temporary non-git directory. If the sdist or wheel configuration
    is incorrect the frontend is silently dropped. Building both artifacts
    explicitly from the source tree (``uv build --sdist`` then
    ``uv build --wheel``) eliminates this failure mode.
    """
    build_recipe = subprocess.run(
        ["just", "--show", "build"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assert "uv build --sdist" in build_recipe and "uv build --wheel" in build_recipe, (
        "just `build` recipe must run `uv build --sdist` and `uv build --wheel` "
        "as separate explicit commands (not bare `uv build`). "
        "Bare `uv build` builds the wheel from the sdist in a temp non-git dir, "
        "which can silently drop the gitignored frontend/ even when `artifacts` is "
        "configured only in [tool.hatch.build.targets.wheel]."
    )


@pytest.mark.slow
def test_real_archives_exclude_generated_state_and_keep_required_files(tmp_path: Path) -> None:
    """Real archives exclude generated state while retaining source, config, license, and SPA files.

    Removing a Hatch exclusion for generated state, such as ``.docgraph/``,
    must make this test fail. The fixture is a gitless copy of tracked source
    plus representative generated files, so it neither depends on nor modifies
    local desktop state.
    """
    project_root = tmp_path / "source-copy"
    project_root.mkdir()
    _copy_tracked_project(project_root)
    gitignore_path = project_root / ".gitignore"
    _ = gitignore_path.write_text(
        gitignore_path.read_text(encoding="utf-8").replace(".cache/\n", ""), encoding="utf-8"
    )
    generated_files = _write_generated_packaging_state(project_root)
    assert all((project_root / path).is_file() for path in generated_files)

    output_directory = tmp_path / "dist"
    output_directory.mkdir()
    environment = os.environ | {"SETUPTOOLS_SCM_PRETEND_VERSION": "0.0.0"}
    for target in ("--sdist", "--wheel"):
        result = subprocess.run(
            ["uv", "build", target, "--out-dir", str(output_directory)],
            cwd=project_root,
            capture_output=True,
            text=True,
            check=False,
            env=environment,
        )
        assert result.returncode == 0, (
            f"uv build {target} failed:\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}"
        )

    sdists = sorted(output_directory.glob("pdomain_ocr_simple_gui-*.tar.gz"))
    wheels = sorted(output_directory.glob("pdomain_ocr_simple_gui-*.whl"))
    assert len(sdists) == 1, f"expected one sdist, got: {sdists}"
    assert len(wheels) == 1, f"expected one wheel, got: {wheels}"

    sdist_members = _sdist_members(sdists[0])
    wheel_members = _wheel_members(wheels[0])
    _assert_members_present(
        members=sdist_members,
        required={
            "LICENSE",
            "README.md",
            "docs/README.md",
            "pyproject.toml",
            "src/pdomain_ocr_simple_gui/__init__.py",
            "src/pdomain_ocr_simple_gui/frontend/assets/app.js",
            "src/pdomain_ocr_simple_gui/frontend/index.html",
        },
        archive_name="sdist",
    )
    _assert_members_present(
        members=wheel_members,
        required={
            "pdomain_ocr_simple_gui/__init__.py",
            "pdomain_ocr_simple_gui/frontend/assets/app.js",
            "pdomain_ocr_simple_gui/frontend/index.html",
            "pdomain_ocr_simple_gui/pdomain-suite.json",
        },
        archive_name="wheel",
    )
    assert any(member.endswith(".dist-info/licenses/LICENSE") for member in wheel_members), (
        "wheel is missing its packaged LICENSE"
    )
    _assert_no_generated_members(members=sdist_members, archive_name="sdist")
    _assert_no_generated_members(members=wheel_members, archive_name="wheel")


